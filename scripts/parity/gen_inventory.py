"""Generate docs/backend-parity/endpoints.md from the reference OpenAPI spec (kernel tags only)."""
import json, pathlib, sys

KERNEL_TAGS = {"Authentication", "Tenancy", "Setup", "User management", "General", "Observability"}
root = pathlib.Path(__file__).resolve().parents[2]
spec = json.loads((root / "apps/api-server/openapi.json").read_text())
METHODS = ("get", "post", "put", "patch", "delete")


def ref_name(s):
    if not s:
        return "-"
    if "$ref" in s:
        return s["$ref"].rsplit("/", 1)[-1]
    if s.get("type") == "array":
        return f"{ref_name(s.get('items'))}[]"
    return s.get("type", "object")


rows = {}
for path, item in sorted(spec["paths"].items()):
    for m in METHODS:
        op = item.get(m)
        if not op:
            continue
        tag = (op.get("tags") or ["?"])[0]
        if tag not in KERNEL_TAGS:
            continue
        body = op.get("requestBody", {}).get("content", {}).get("application/json", {}).get("schema")
        ok = next((c for c in op["responses"] if c.startswith("2")), "200")
        resp = op["responses"][ok].get("content", {}).get("application/json", {}).get("schema")
        public = op.get("security") == []
        errs = ",".join(sorted(c for c in op["responses"] if not c.startswith("2")))
        rows.setdefault(tag, []).append(
            f"| `{m.upper()}` | `{path}` | {'public' if public else 'bearer'} | {ref_name(body)} | {ok} {ref_name(resp)} | {errs} | `{op.get('operationId','')}` |"
        )

out = ["# Kernel endpoint inventory", "",
       "_Generated by `scripts/parity/gen_inventory.py` from `apps/api-server/openapi.json`. Do not edit by hand._", ""]
total = 0
for tag in sorted(rows):
    out += [f"## {tag} ({len(rows[tag])})", "",
            "| Method | Path | Auth | Request | Success response | Error codes | operationId |",
            "| --- | --- | --- | --- | --- | --- | --- |", *rows[tag], ""]
    total += len(rows[tag])
out.insert(2, f"**Total kernel operations: {total}**\n")
dest = root / "docs/backend-parity/endpoints.md"
dest.write_text("\n".join(out))
print(total, "operations ->", dest)
