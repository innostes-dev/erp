/** Icon component for a module or plugin id. */
export function appIcon(id: string): LucideIcon {
  return APP_ICONS[id] ?? (id in PAGE_ICONS ? PAGE_ICONS[id] : LayoutGrid);
}

/** Icon component for a sub-page id. */
export function pageIcon(id: string): LucideIcon {
  return PAGE_ICONS[id] ?? CircleDot;
}

/** Icon for an unknown plugin. */
export const PluginIcon = Puzzle;
