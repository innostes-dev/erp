// Builds components/demos/registry.ts from every file in components/demos/**.tsx, so the docs
// can render any demo by name (e.g. "overlays/dialog/basic") and show its exact source.
// Runs before `next dev` and `next build`.

import { globSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const demosDir = join(root, 'components', 'demos');

const files = globSync('**/*.tsx', { cwd: demosDir })
  .map((f) => f.replaceAll('\\', '/'))
  .filter((f) => f !== 'registry.tsx')
  .sort();

const toIdent = (name) => 'Demo_' + name.replace(/[^a-zA-Z0-9]/g, '_');

const lines = [
  '// Generated by scripts/generate-demo-registry.mjs. Do not edit.',
  "import type { ComponentType } from 'react';",
  ...files.map(
    (f) => `import ${toIdent(f)} from './${f.replace(/\.tsx$/, '')}';`,
  ),
  '',
  'export const demos: Record<string, ComponentType> = {',
  ...files.map((f) => `  '${f.replace(/\.tsx$/, '')}': ${toIdent(f)},`),
  '};',
  '',
];

writeFileSync(join(demosDir, 'registry.ts'), lines.join('\n'));
console.log(`demo registry: ${files.length} demos`);
